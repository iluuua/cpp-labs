// Лаба 1, задание 1: вывод строк в консоль.
// По условию прокомментирована каждая строка, включая #include и скобку main.

#include <iostream>    // std::cout и всё остальное для ввода-вывода
#include "console.h"   // setupConsole(), чтобы в Windows не было кракозябр вместо кириллицы

int main() {                                        // отсюда начинается выполнение программы
    setupConsole();                                 // включаем UTF-8 в консоли (в Windows без этого русский текст ломается)
    std::cout << "First string\n";                  // \n переводит курсор на новую строку
    std::cout << "Первая строка\nВторая строка\n";  // две строки за один вывод, между ними \n
    std::cout << "Спецсимволы \"\\\"\n";            // кавычку и обратный слэш экранируем: \" и \\, иначе компилятор поймёт их по-своему
    return 0;                                       // 0 значит, что программа завершилась без ошибок
}                                                   // конец функции main
